export function searchSP500(query: string, limit: number = 8): SP500Company[] {
  if (!query.trim()) return [];

  const q = query.toLowerCase().trim();

  // Exact symbol match first
  const exactMatch = SP500_COMPANIES.filter(
    (c) => c.symbol.toLowerCase() === q
  );

  // Symbol starts-with
  const symbolStartsWith = SP500_COMPANIES.filter(
    (c) => c.symbol.toLowerCase().startsWith(q) && c.symbol.toLowerCase() !== q
  );

  // Name contains
  const nameContains = SP500_COMPANIES.filter(
    (c) =>
      c.name.toLowerCase().includes(q) &&
      !c.symbol.toLowerCase().startsWith(q) &&
      c.symbol.toLowerCase() !== q
  );

  // Symbol contains (but doesn't start with)
  const symbolContains = SP500_COMPANIES.filter(
    (c) =>
      c.symbol.toLowerCase().includes(q) &&
      !c.symbol.toLowerCase().startsWith(q) &&
      c.symbol.toLowerCase() !== q &&
      !c.name.toLowerCase().includes(q)
  );

  return [...exactMatch, ...symbolStartsWith, ...nameContains, ...symbolContains].slice(0, limit);
}
